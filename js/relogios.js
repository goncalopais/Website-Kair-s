// 13900 → "13 900 €"
function formatarPreco(valor) {
  return valor.toLocaleString("pt-PT", {
    style: "currency",
    currency: "EUR",
    maximumFractionDigits: 0,
  });
}

// Cria o cartão de um relógio
function criarCartao(relogio) {
  const selo = relogio.novidade ? `<span class="cartao__selo">Novidade</span>` : "";
  const extra = relogio.caixaPapeis ? "Caixa e papéis" : relogio.estado;

  const cartao = document.createElement("li");
  cartao.innerHTML = `
    <article class="cartao">
      <div class="cartao__topo">
        <img src="img/relogios/${relogio.id}.svg"
             alt="Ilustração do relógio ${relogio.marca} ${relogio.modelo}"
             class="cartao__imagem" width="400" height="400" loading="lazy">
        ${selo}
      </div>
      <div class="cartao__corpo">
        <h3>${relogio.marca} · ${relogio.modelo}</h3>
        <p>Ref. ${relogio.referencia} · ${relogio.ano} · ${extra}</p>
        <div class="cartao__rodape">
          <span class="preco">${formatarPreco(relogio.preco)}</span>
          <a href="relogio.html?id=${relogio.id}" class="cartao__link">Ver relógio →</a>
        </div>
      </div>
    </article>
  `;

  return cartao;
}
